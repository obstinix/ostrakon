// Generates typed ABI + bytecode modules from the forge build output.
// Writes only when content changes, so the Vite dev server does not reload needlessly.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath = join(root, "contracts/out/Ostrakon.sol/Ostrakon.json");
const outDir = join(root, "web/src/generated");

if (!existsSync(artifactPath)) {
  console.error(`gen-abi: ${artifactPath} not found. Run "forge build" first.`);
  process.exit(1);
}

const artifact = JSON.parse(readFileSync(artifactPath, "utf8")) as {
  abi: unknown[];
  bytecode: { object: `0x${string}` };
};

const header = "// AUTO-GENERATED by scripts/gen-abi.ts from contracts/out. Do not edit.\n";
const files: Record<string, string> = {
  "ostrakonAbi.ts": `${header}export const ostrakonAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  "ostrakonBytecode.ts": `${header}export const ostrakonBytecode = "${artifact.bytecode.object}" as const;\n`,
};

mkdirSync(outDir, { recursive: true });
for (const [name, content] of Object.entries(files)) {
  const p = join(outDir, name);
  if (existsSync(p) && readFileSync(p, "utf8") === content) continue;
  writeFileSync(p, content);
  console.log(`gen-abi: wrote web/src/generated/${name}`);
}
